// Icon generator: merges Resolve's icon paths with Forma UI's own and writes the module that `Icon` draws from.
//
//   node --experimental-strip-types --disable-warning=ExperimentalWarning --disable-warning=MODULE_TYPELESS_PACKAGE_JSON \
//     scripts/build-icons.ts
//
// The second warning is switched off because Resolve's copy lives under design/, outside any package with a `type`.
//
// Two sources, two owners:
//   design/resolve-c3f02f8/icon-paths.ts   the verified copy of Resolve's `Icon/paths.ts`; never edited.
//   icons/forma-icons.ts                   the icons Forma UI draws itself, and `filledIcons`, the names (of either
//                                          source) that Icon paints with a fill; the place to add or change one.
// A name in both is an error: an icon has one owner. Output (deterministic: names in alphabetical order, fixed
// formatting, no timestamps):
//   src/components/Icon/paths.ts   `iconPaths`, `IconName`, `iconNames` and `filledIconNames`. Committed; CI
//                                  regenerates it and fails on any diff.
//
// The script sticks to erasable TypeScript, so type stripping can run it (see build-tokens.ts).
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { isMainModule, write } from './script-utils.ts'

export const RESOLVE_SOURCE = 'design/resolve-c3f02f8/icon-paths.ts'
export const FORMA_SOURCE = 'icons/forma-icons.ts'
export const OUTPUT = 'src/components/Icon/paths.ts'

export type IconPaths = Record<string, readonly string[]>

// An icon name is a CSS-friendly word, and a path is SVG path data: letters of commands, numbers and separators.
// Anything else would need escaping in the generated string literals, and cannot come from a Figma export.
const NAME = /^[a-z][a-z0-9-]*$/
const PATH_DATA = /^[MmLlHhVvCcSsQqTtAaZz0-9eE.,\s+-]+$/

/** Checks the shape of the source and returns it; throws on the first problem, naming the icon. */
export function validate(source: unknown): IconPaths {
  if (typeof source !== 'object' || source === null || Object.keys(source).length === 0) {
    throw new Error('An icon source must export an object with at least one icon')
  }
  // The result is built entry by entry, so that its type comes from the checks and not from a cast.
  const iconPaths: IconPaths = {}
  for (const [name, paths] of Object.entries(source)) {
    if (!NAME.test(name)) throw new Error(`Icon name "${name}" must be lowercase words joined by "-"`)
    if (!Array.isArray(paths) || paths.length === 0) throw new Error(`Icon "${name}" needs at least one path`)
    const checked: string[] = []
    for (const d of paths) {
      if (typeof d !== 'string' || !PATH_DATA.test(d)) throw new Error(`Icon "${name}" has an invalid path: ${d}`)
      checked.push(d)
    }
    iconPaths[name] = checked
  }
  return iconPaths
}

/** Checks that each filled icon is drawn, once, so that `filledIconNames` can only hold names of the table. */
export function validateFilled(filledIcons: readonly string[], iconPaths: IconPaths): void {
  for (const name of filledIcons) {
    if (!Object.hasOwn(iconPaths, name)) throw new Error(`Filled icon "${name}" is not drawn in either source`)
  }
  if (new Set(filledIcons).size !== filledIcons.length) throw new Error('A filled icon is named twice')
}

/** The text of `paths.ts` for these icons; `filledIcons` is empty unless the caller names some. */
export function generate(source: IconPaths, filledIcons: readonly string[] = []): string {
  const iconPaths = validate(source)
  validateFilled(filledIcons, iconPaths)
  const icons = Object.entries(iconPaths).map(([name, paths]) => {
    const lines = paths.map((d) => `    '${d}',`)
    return `  ${name.includes('-') ? `'${name}'` : name}: [\n${lines.join('\n')}\n  ],`
  })
  return [
    `// Generated by scripts/build-icons.ts from ${RESOLVE_SOURCE} and ${FORMA_SOURCE}. Do not edit by hand.`,
    'export const iconPaths = {',
    ...icons,
    '} as const',
    '',
    'export type IconName = keyof typeof iconPaths',
    '',
    '/** Every icon name, in alphabetical order, which is also the order of the table above. */',
    'export const iconNames: readonly IconName[] = [',
    ...Object.keys(iconPaths).map((name) => `  '${name}',`),
    ']',
    '',
    '/** The icons drawn with a fill as well as a stroke. The set is outline only, so each one is an exception. */',
    'export const filledIconNames: readonly IconName[] = [',
    ...filledIcons.map((name) => `  '${name}',`),
    ']',
    '',
  ].join('\n')
}

/**
 * Joins the icons of Resolve and of Forma UI into one table in alphabetical order, which is `iconNames` order.
 * Resolve's table is already alphabetical, so its icons keep their relative order. A name in both throws.
 */
export function merge(resolveIcons: IconPaths, formaIcons: IconPaths): IconPaths {
  for (const name of Object.keys(formaIcons)) {
    if (name in resolveIcons) throw new Error(`Icon "${name}" is in ${RESOLVE_SOURCE} and in ${FORMA_SOURCE}`)
  }
  return Object.fromEntries(Object.entries({ ...resolveIcons, ...formaIcons }).sort(([a], [b]) => (a < b ? -1 : 1)))
}

/** Reads one source by importing the module: the file is data in TypeScript syntax, not a format to parse. */
async function loadModule(repoRoot: string, file: string, exportName: string): Promise<IconPaths> {
  const module: Record<string, unknown> = await import(pathToFileURL(join(repoRoot, file)).href)
  return validate(module[exportName])
}

/** Both sources, merged. `repoRoot` locates Resolve's copy and `packageRoot` Forma UI's own file. */
export async function loadSource(
  repoRoot: string,
  packageRoot = join(repoRoot, 'packages', 'forma-ui'),
): Promise<IconPaths> {
  return merge(
    await loadModule(repoRoot, RESOLVE_SOURCE, 'iconPaths'),
    await loadModule(packageRoot, FORMA_SOURCE, 'formaIcons'),
  )
}

/** The names `forma-icons.ts` marks as filled. */
export async function loadFilled(packageRoot: string): Promise<readonly string[]> {
  const module: Record<string, unknown> = await import(pathToFileURL(join(packageRoot, FORMA_SOURCE)).href)
  const names = module.filledIcons
  if (!Array.isArray(names) || !names.every((name) => typeof name === 'string')) {
    throw new Error(`${FORMA_SOURCE} must export filledIcons, a list of icon names`)
  }
  return names
}

export async function main(root: string, repoRoot = resolve(root, '..', '..')): Promise<void> {
  write(join(root, OUTPUT), generate(await loadSource(repoRoot), await loadFilled(root)))
}

if (isMainModule(import.meta.filename)) {
  try {
    await main(resolve(import.meta.dirname, '..'))
  } catch (error) {
    console.error(error instanceof Error ? error.message : error)
    process.exitCode = 1
  }
}
