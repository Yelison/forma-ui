import { readFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { describe, expect, it } from 'vitest'
import {
  FORMA_SOURCE,
  OUTPUT,
  RESOLVE_SOURCE,
  generate,
  loadFilled,
  loadSource,
  merge,
  validate,
  validateFilled,
} from '../../../scripts/build-icons.ts'
import { iconNames as exportedIconNames } from '../../index.ts'
import { filledIconNames, iconNames, iconPaths } from './paths.ts'

const packageRoot = resolve(import.meta.dirname, '../../..')
const repoRoot = resolve(packageRoot, '..', '..')

describe('icon generator', () => {
  it('writes the committed paths.ts, so CI fails on a stale file or an icon added there by hand', async () => {
    const committed = readFileSync(join(packageRoot, OUTPUT), 'utf8')

    expect(generate(await loadSource(repoRoot), await loadFilled(packageRoot))).toBe(committed)
  })

  it('names the source in the header and ends the file with a newline', async () => {
    const text = generate(await loadSource(repoRoot))

    expect(text.split('\n', 1)[0]).toBe(
      `// Generated by scripts/build-icons.ts from ${RESOLVE_SOURCE} and ${FORMA_SOURCE}. Do not edit by hand.`,
    )
    expect(text.endsWith('\n')).toBe(true)
  })

  it.each([
    { owner: 'Resolve', file: RESOLVE_SOURCE, root: repoRoot, exportName: 'iconPaths', count: 23 },
    { owner: 'Forma UI', file: FORMA_SOURCE, root: packageRoot, exportName: 'formaIcons', count: 21 },
  ])('ships the $count icons of $owner as its source draws them, in the same order', async (source) => {
    const module = await import(pathToFileURL(join(source.root, source.file)).href)
    const drawn: Record<string, readonly string[]> = module[source.exportName]

    expect(Object.keys(drawn)).toHaveLength(source.count)
    expect(Object.entries(iconPaths).filter(([name]) => name in drawn)).toEqual(Object.entries(drawn))
  })

  it('lists in iconNames exactly the names of the table, once each, in alphabetical order', () => {
    expect(iconNames).toEqual(Object.keys(iconPaths))
    expect(iconNames).toEqual([...iconNames].sort())
    expect(new Set(iconNames).size).toBe(iconNames.length)
  })

  it('merges two sources in alphabetical order, whichever source an icon comes from', () => {
    const merged = merge({ arrow: ['M0 0'], plus: ['M1 1'] }, { check: ['M2 2'], zoom: ['M3 3'] })

    expect(Object.keys(merged)).toEqual(['arrow', 'check', 'plus', 'zoom'])
  })

  it('refuses a name that both sources draw, because an icon has one owner', () => {
    expect(() => merge({ arrow: ['M0 0'] }, { arrow: ['M1 1'] })).toThrow(/Icon "arrow" is in .* and in /)
  })

  it('exports iconNames from the package entry point', () => {
    expect(exportedIconNames).toBe(iconNames)
  })

  it('writes iconNames from the icons it is given, so that the list cannot drift from the table', () => {
    const text = generate({ arrow: ['M0 0'], 'arrow-left': ['M1 1'] })

    expect(text).toContain("export const iconNames: readonly IconName[] = [\n  'arrow',\n  'arrow-left',\n]")
  })

  it('is deterministic: the same input gives the same text', async () => {
    const source = await loadSource(repoRoot)

    expect(generate(source)).toBe(generate(structuredClone(source)))
  })

  it('rejects a source that is not an object of icons', () => {
    for (const bad of [undefined, null, {}, 'icons']) expect(() => validate(bad)).toThrow(/at least one icon/)
  })

  it('rejects an icon without paths, with a name that is not lowercase, or with path data it cannot quote', () => {
    expect(() => validate({ arrow: [] })).toThrow(/Icon "arrow" needs at least one path/)
    expect(() => validate({ Arrow: ['M0 0'] })).toThrow(/Icon name "Arrow"/)
    expect(() => validate({ arrow: ["M0 0'"] })).toThrow(/Icon "arrow" has an invalid path/)
  })

  it('quotes a name that is not a plain identifier', () => {
    expect(generate({ 'arrow-left': ['M15 5L8 12L15 19'] })).toContain(
      "  'arrow-left': [\n    'M15 5L8 12L15 19',\n  ],",
    )
  })

  it('ships the 13 icons agreed in 0.7, whatever the size of the set grows to', () => {
    expect(iconNames).toEqual(
      expect.arrayContaining([
        ...['trash', 'share', 'folder-plus', 'pencil', 'eye', 'monitor'],
        ...['bold', 'italic', 'code', 'heading-2', 'heading-3', 'list-ordered', 'star-filled'],
      ]),
    )
  })

  it('lists in filledIconNames the icons that are filled, and writes them from the source', async () => {
    expect(filledIconNames).toEqual(await loadFilled(packageRoot))
    expect(generate({ star: ['M0 0'], 'star-filled': ['M0 0'] }, ['star-filled'])).toContain(
      "export const filledIconNames: readonly IconName[] = [\n  'star-filled',\n]",
    )
    expect(generate({ star: ['M0 0'] })).toContain('export const filledIconNames: readonly IconName[] = [\n]')
  })

  it('refuses a filled icon that no source draws, or one named twice', () => {
    expect(() => validateFilled(['ghost'], { star: ['M0 0'] })).toThrow(/Filled icon "ghost" is not drawn/)
    expect(() => validateFilled(['star', 'star'], { star: ['M0 0'] })).toThrow(/named twice/)
  })

  it('does not take a name that every object inherits for an icon that is drawn', () => {
    expect(() => validateFilled(['constructor'], { star: ['M0 0'] })).toThrow(/Filled icon "constructor"/)
  })
})
